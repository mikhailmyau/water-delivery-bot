"""Виды питьевой воды, которые продаёт бот."""

from __future__ import annotations

import enum


class WaterType(str, enum.Enum):
    """Аббревиатуры приняты у заказчика и используются как есть в текстах бота."""

    SLM = "slm"
    """Слабоминерализованная, негазированная."""

    SRM = "srm"
    """Среднеминерализованная, негазированная."""

    GAZ = "gaz"
    """Газированная."""
